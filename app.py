# ----------------------------- 6. SELECCIÓN AUTOMÁTICA DE MODELO -------------
def spatial_model_selection(y, X, w, name_y, name_x):
    """Rutina completa: OLS + LM/RLM + SAR + SEM + SAC + SDM → elige el mejor"""
    results = {}

    # 1. OLS + diagnósticos espaciales
    ols = OLS(y, X, w=w, spat_diag=True, moran=True, name_y=name_y, name_x=name_x)
    results['OLS'] = {
        'model': ols, 'aic': ols.aic,
        'lm_lag_p': ols.lm_lag[1] if hasattr(ols,'lm_lag') else 1,
        'lm_error_p': ols.lm_error[1] if hasattr(ols,'lm_error') else 1,
        'rlm_lag_p': ols.rlm_lag[1] if hasattr(ols,'rlm_lag') else 1,
        'rlm_error_p': ols.rlm_error[1] if hasattr(ols,'rlm_error') else 1
    }

    # 2. SAR
    try:
        sar = ML_Lag(y, X, w=w, name_y=name_y, name_x=name_x)
        results['SAR'] = {'model': sar, 'aic': sar.aic, 'rho': sar.rho}
    except Exception as e:
        results['SAR'] = {'error': str(e)}

    # 3. SEM
    try:
        sem = ML_Error(y, X, w=w, name_y=name_y, name_x=name_x)
        results['SEM'] = {'model': sem, 'aic': sem.aic, 'lambda': sem.lam}
    except Exception as e:
        results['SEM'] = {'error': str(e)}

    # 4. SAC (SARAR)
    try:
        sac = GM_Combo(y, X, w=w, name_y=name_y, name_x=name_x)
        results['SAC'] = {'model': sac, 'aic': getattr(sac,'aic',np.nan)}
    except Exception as e:
        results['SAC'] = {'error': str(e)}

    # 5. SDM (Spatial Durbin = SAR + WX)
    try:
        WX = lag_spatial(w, X)
        X_sdm = np.hstack([X, WX])
        name_sdm = name_x + [f'W_{n}' for n in name_x]
        sdm = ML_Lag(y, X_sdm, w=w, name_y=name_y, name_x=name_sdm)
        results['SDM'] = {'model': sdm, 'aic': sdm.aic, 'rho': sdm.rho}
    except Exception as e:
        results['SDM'] = {'error': str(e)}

    # ----- Decisión -----
    lm = results['OLS']
    decision = 'OLS'
    reason = []

    if lm['rlm_lag_p'] < 0.05 and lm['rlm_error_p'] >= 0.05:
        decision = 'SAR'
        reason.append("RLM-Lag significativo, RLM-Error no")
    elif lm['rlm_error_p'] < 0.05 and lm['rlm_lag_p'] >= 0.05:
        decision = 'SEM'
        reason.append("RLM-Error significativo, RLM-Lag no")
    elif lm['rlm_lag_p'] < 0.05 and lm['rlm_error_p'] < 0.05:
        aics = {m: results[m]['aic'] for m in ['SAR','SEM','SAC','SDM']
                if m in results and 'aic' in results[m] and not np.isnan(results[m].get('aic',np.nan))}
        if aics:
            decision = min(aics, key=aics.get)
            reason.append(f"Ambos RLM significativos → menor AIC: {decision}")
        else:
            decision = 'SAC'
            reason.append("Ambos RLM significativos → SAC por defecto")
    else:
        reason.append("Ningún RLM significativo → OLS")

    # Preferir SDM si mejora AIC de forma clara
    if 'SDM' in results and 'aic' in results['SDM']:
        best_other = min([results[m].get('aic',np.inf) for m in ['SAR','SEM','SAC','OLS'] if m in results and 'aic' in results[m]], default=np.inf)
        if results['SDM']['aic'] < best_other - 2:
            decision = 'SDM'
            reason.append("SDM mejora AIC > 2 puntos")

    print(f"\n{'='*60}")
    print(f"SELECCIÓN DE MODELO → {name_y}")
    print(f"{'='*60}")
    print(f"LM-Lag p = {lm['lm_lag_p']:.4f} | LM-Error p = {lm['lm_error_p']:.4f}")
    print(f"RLM-Lag p = {lm['rlm_lag_p']:.4f} | RLM-Error p = {lm['rlm_error_p']:.4f}")
    print(f">>> Modelo elegido: {decision}")
    print(f"    Razones: {' | '.join(reason)}")
    return decision, results

print("\n>>> Diagnóstico ecuación PIB")
