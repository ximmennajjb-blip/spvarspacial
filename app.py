def build_candidate_weights(gdf_proj, k_values=[4, 5, 6], thresholds=None):
    """Construye un diccionario de matrices W candidatas."""
    weights = {}

    # Contigüidad
    weights['queen'] = Queen.from_dataframe(gdf_proj, use_index=False)
    weights['rook'] = Rook.from_dataframe(gdf_proj, use_index=False)

    # k-NN
    for k in k_values:
        weights[f'knn_{k}'] = KNN.from_dataframe(gdf_proj, k=k, use_index=False)

    # Distancia inversa (bandas)
    centroids = np.array([[p.x, p.y] for p in gdf_proj.geometry.centroid])
    from scipy.spatial.distance import pdist
    dists = pdist(centroids)
    if thresholds is None:
        thresholds = [np.percentile(dists, p) for p in [25, 40, 55]]

    for i, thr in enumerate(thresholds):
        try:
            w = DistanceBand.from_dataframe(gdf_proj, threshold=thr, binary=False,
                                            alpha=-1.0, use_index=False)
            weights[f'invdist_{i}'] = w
        except Exception as e:
            print(f"No se pudo crear invdist_{i}: {e}")

    # Estandarización por filas
    for name, w in weights.items():
        w.transform = 'r'
        # Verificar
        row_sums = np.array(w.full()[0].sum(axis=1)).flatten()
        if not np.allclose(row_sums, 1.0, atol=1e-6):
            print(f"⚠ {name}: suma de filas no es 1 (posible isla o problema)")

    return weights

