def lisa_label(lisa):
    labs = []
    for i in range(len(lisa.q)):
        if lisa.p_sim[i] > 0.05: labs.append("No significativo")
        elif lisa.q[i]==1: labs.append("High-High")
        elif lisa.q[i]==2: labs.append("Low-High")
        elif lisa.q[i]==3: labs.append("Low-Low")
        else: labs.append("High-Low")
    return labs

