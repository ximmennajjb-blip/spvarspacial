# CELDA 10: Impactos directos, indirectos y totales (LeSage & Pace)
# =============================================================================
def compute_impacts(model, w, model_type, var_names):
    """
    Calcula impactos promedio directos, indirectos y totales
    siguiendo LeSage & Pace (2009).
    Solo aplicable a SAR / SDM / SAC.
    """
    if model_type not in ['SAR', 'SDM', 'SAC']:
        print(f"Impactos espaciales no aplicables a {model_type}")
        return None

    try:
        # Usar el método built-in de spreg si está disponible
        if hasattr(model, 'predy_e') or hasattr(model, 'spat_impacts'):
            # En versiones recientes de spreg
            impacts = getattr(model, 'spat_impacts', None)
            if impacts is not None:
                return impacts
    except:
        pass

    # Cálculo manual (aproximación power series o inversa)
    n = w.n
    rho = getattr(model, 'rho', 0.0)
    if rho is None:
        rho = 0.0

    # Matriz de impactos S = (I - ρW)^{-1}
    W_full = w.full()[0]
    try:
        S = inv(np.eye(n) - rho * W_full)
    except np.linalg.LinAlgError:
        print("Error de inversión: usando aproximación de series de potencias")
        S = np.eye(n)
        Wpow = np.eye(n)
        for k in range(1, 50):
            Wpow = Wpow @ W_full
            S += (rho ** k) * Wpow
            if np.abs(rho)**k < 1e-8:
                break

    # Coeficientes β (excluyendo constante y ρ)
    betas = model.betas.flatten()
    # En ML_Lag el primer coeficiente es el intercepto, luego β, luego ρ
    # Ajustar según tipo
    if model_type in ['SAR', 'SDM']:
        beta = betas[1:-1]  # quitar intercepto y rho
    else:
        beta = betas[1:]    # solo quitar intercepto

    # Para SDM hay coeficientes de WX también
    n_x = len(var_names)
    if model_type == 'SDM' and len(beta) == 2 * n_x:
        beta_x = beta[:n_x]
        beta_wx = beta[n_x:]
    else:
        beta_x = beta[:n_x]
        beta_wx = np.zeros(n_x)

    impacts = {}
    for i, vname in enumerate(var_names):
        # Matriz de efectos parciales
        # ∂y/∂x_r = S * (β_r I + θ_r W)
        M = S @ (beta_x[i] * np.eye(n) + beta_wx[i] * W_full)

        direct = np.mean(np.diag(M))
        total = np.mean(M.sum(axis=1))
        indirect = total - direct

        impacts[vname] = {
            'direct': direct,
            'indirect': indirect,
            'total': total
        }

    return impacts

print("\n>>> Impactos espaciales - Ecuación PIB")
