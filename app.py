def select_best_W(df, gdf, W_candidates, var='log_PIB', year=2022):
    """
    Selecciona la mejor W maximizando |I de Moran| de residuales OLS
    y minimizando AIC de un modelo espacial simple.
    """
    # Cross-section del año más reciente
    df_cs = df[df['YEAR'] == year].copy()
    df_cs = df_cs.merge(gdf[['COD_DPTO']], on='COD_DPTO', how='inner')
    df_cs = df_cs.set_index('COD_DPTO').reindex(gdf['COD_DPTO']).reset_index()

    y = df_cs[var].values.reshape(-1, 1)
    X = df_cs[['luces_viirs', 'log_poblacion', 'urbanizacion']].values
    X = np.column_stack((np.ones(len(X)), X))  # constante

    results = []
    for name, w in W_candidates.items():
        try:
            # OLS + Moran residual
            ols = OLS(y, X[:, 1:], w=w, spat_diag=True, moran=True, name_y=var)
            moran_I = ols.moran_res[0] if hasattr(ols, 'moran_res') else np.nan
            moran_p = ols.moran_res[2] if hasattr(ols, 'moran_res') else np.nan

            # AIC de SAR simple (ML)
            try:
                sar = ML_Lag(y, X[:, 1:], w=w, name_y=var, name_x=['luces', 'log_pop', 'urban'])
                aic = sar.aic
            except:
                aic = np.nan

            results.append({
                'W': name,
                'Moran_I': moran_I,
                'Moran_p': moran_p,
                'AIC_SAR': aic,
                'n': w.n
            })
        except Exception as e:
            print(f"Error en {name}: {e}")

    res_df = pd.DataFrame(results)
    # Score: mayor |Moran| + menor AIC (normalizado)
    res_df['score'] = res_df['Moran_I'].abs() - 0.01 * (res_df['AIC_SAR'] - res_df['AIC_SAR'].min())
    best = res_df.loc[res_df['score'].idxmax()]

    print("\n=== Ranking de matrices W ===")
    print(res_df.sort_values('score', ascending=False).to_string(index=False))
    print(f"\n>>> Mejor W seleccionada: {best['W']}")

    return W_candidates[best['W']], best['W'], res_df

W_best, W_name, W_ranking = select_best_W(df, gdf, W_candidates, var='log_PIB', year=2022)
