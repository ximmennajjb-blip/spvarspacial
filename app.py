def export_results_tables(model_pib, model_hom, decision_pib, decision_hom,
                          impacts_pib, impacts_hom, W_name):
    """Genera y guarda tablas limpias de coeficientes e impactos."""

    def model_to_table(model, decision, name):
        rows = []
        betas = model.betas.flatten()
        std_err = model.std_err.flatten() if hasattr(model, 'std_err') else np.full_like(betas, np.nan)
        tstat = model.z_stat if hasattr(model, 'z_stat') else None

        var_names = ['const'] + (model.name_x if hasattr(model, 'name_x') else [])
        if decision in ['SAR', 'SDM'] and hasattr(model, 'rho'):
            # rho suele estar al final
            pass

        for i, vname in enumerate(var_names[:len(betas)]):
            se = std_err[i] if i < len(std_err) else np.nan
            t = (betas[i]/se) if se and se > 0 else np.nan
            p = 2*(1 - stats.norm.cdf(abs(t))) if not np.isnan(t) else np.nan
            rows.append({
                'Variable': vname,
                'Coeficiente': betas[i],
                'Error_Est': se,
                't/z': t,
                'p_valor': p,
                'Modelo': decision,
                'Ecuacion': name
            })
        return pd.DataFrame(rows)

    tab_pib = model_to_table(model_pib, decision_pib, 'PIB')
    tab_hom = model_to_table(model_hom, decision_hom, 'Homicidios')
    coef_table = pd.concat([tab_pib, tab_hom], ignore_index=True)

    # Impactos
    imp_rows = []
    for eq, imp_dict, dec in [('PIB', impacts_pib, decision_pib),
                               ('Homicidios', impacts_hom, decision_hom)]:
        if imp_dict:
            for var, vals in imp_dict.items():
                imp_rows.append({
                    'Ecuacion': eq,
                    'Variable': var,
                    'Directo': vals['direct'],
                    'Indirecto': vals['indirect'],
                    'Total': vals['total'],
                    'Modelo': dec
                })
    imp_table = pd.DataFrame(imp_rows)

    # Guardar
    coef_table.to_csv('coeficientes_spvar.csv', index=False)
    imp_table.to_csv('impactos_espaciales.csv', index=False)

    print("=== Tabla de Coeficientes ===")
    print(coef_table.round(4).to_string(index=False))

    print("\n=== Tabla de Impactos (LeSage-Pace) ===")
    print(imp_table.round(4).to_string(index=False))

    print(f"\nArchivos exportados: coeficientes_spvar.csv | impactos_espaciales.csv")
    print(f"Matriz W utilizada: {W_name}")

    return coef_table, imp_table

