    if variable == 'log_PIB':
        fill_color, name = 'Spectral', 'log(PIB)'
    elif variable == 'luces_viirs':
        fill_color, name = 'YlOrRd', 'Luces VIIRS'
    else:
        fill_color, name = 'YlOrRd', 'Tasa Homicidios'

    folium.Choropleth(
        geo_data=gdf_map,
        name=name,
        data=gdf_map,
        columns=['COD_DPTO', variable],
        key_on='feature.properties.COD_DPTO',
        fill_color=fill_color,
        fill_opacity=0.82,
        line_opacity=0.45,
        legend_name=name,
        highlight=True
    ).add_to(m)

    folium.GeoJson(
        gdf_map,
        style_function=lambda x: {'fillColor': 'transparent', 'color': '#222', 'weight': 0.6},
        tooltip=folium.GeoJsonTooltip(
            fields=['DEPARTAMENTO', 'log_PIB', 'tasa_homicidios', 'luces_viirs', 'LISA_PIB', 'LISA_HOM'],
            aliases=['Departamento:', 'log(PIB):', 'Homicidios:', 'Luces:', 'LISA PIB:', 'LISA Hom:'],
            sticky=True,
            labels=True
        )
    ).add_to(m)

    folium.LayerControl().add_to(m)

    path = f'mapa_folium_{variable}.html'
    m.save(path)
    return path

