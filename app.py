def audit_data(df, gdf):
    """Auditoría completa de calidad de datos."""
    report = {}

    # 1. Nulos
    nulls = df.isnull().sum()
    report['nulls'] = nulls[nulls > 0].to_dict()
    if len(report['nulls']) == 0:
        print("✓ Sin valores nulos")
    else:
        print("⚠ Valores nulos encontrados:", report['nulls'])

    # 2. Duplicados
    dups = df.duplicated(subset=['COD_DPTO', 'YEAR']).sum()
    report['duplicados'] = dups
    print(f"{'✓' if dups==0 else '⚠'} Duplicados (COD_DPTO+YEAR): {dups}")

    # 3. Cobertura espacial
    missing_geom = set(df['COD_DPTO'].unique()) - set(gdf['COD_DPTO'].unique())
    report['sin_geometria'] = list(missing_geom)
    print(f"{'✓' if len(missing_geom)==0 else '⚠'} Departamentos sin geometría: {len(missing_geom)}")

    # 4. Estacionariedad (promedio por año + ADF por departamento)
    print("\n--- Pruebas de estacionariedad (ADF) ---")
    adf_results = {}
    for var in ['log_PIB', 'tasa_homicidios', 'luces_viirs']:
        pvals = []
        for depto in df['COD_DPTO'].unique():
            series = df.loc[df['COD_DPTO']==depto, var].values
            if len(series) > 5:
                try:
                    pval = adfuller(series, autolag='AIC')[1]
                    pvals.append(pval)
                except:
                    pass
        adf_results[var] = {
            'mean_pval': np.mean(pvals) if pvals else np.nan,
            'pct_stationary_5pct': np.mean(np.array(pvals) < 0.05)*100 if pvals else np.nan
        }
        print(f"{var}: p-valor medio ADF = {adf_results[var]['mean_pval']:.3f} | "
              f"% estacionarias (5%): {adf_results[var]['pct_stationary_5pct']:.1f}%")
    report['adf'] = adf_results

    # 5. Multicolinealidad (VIF sobre variables de control)
    print("\n--- VIF (multicolinealidad) ---")
    X_vif = df[['luces_viirs', 'log_poblacion', 'densidad', 'urbanizacion']].dropna()
    X_vif = (X_vif - X_vif.mean()) / X_vif.std()  # estandarizar
    vif_data = pd.DataFrame({
        'variable': X_vif.columns,
        'VIF': [variance_inflation_factor(X_vif.values, i) for i in range(X_vif.shape[1])]
    })
    print(vif_data.to_string(index=False))
    report['vif'] = vif_data.to_dict('records')

    return report

