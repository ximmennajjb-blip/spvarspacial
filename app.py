def load_colombia_departments():
    urls = [
        "https://raw.githubusercontent.com/caticoa3/colombia_mapa/master/co_2018_MGN_DPTO_POLITICO.geojson",
        "https://raw.githubusercontent.com/santiblanko/colombia.geojson/master/depto.json"
    ]
    gdf = None
    for url in urls:
        try:
            gdf = gpd.read_file(url)
            break
        except: continue
    if gdf is None:
        raise RuntimeError("No se pudo cargar geometría")
    rename = {}
    for c in gdf.columns:
        cl = c.lower()
        if any(x in cl for x in ['nombre','name','dpto_cnmbr','nom_dep']): rename[c]='DEPARTAMENTO'
        elif any(x in cl for x in ['codigo','cod','dpto_ccdgo','cod_dep']): rename[c]='COD_DPTO'
    gdf = gdf.rename(columns=rename)
    if 'DEPARTAMENTO' not in gdf.columns: gdf['DEPARTAMENTO'] = gdf.index.astype(str)
    if 'COD_DPTO' not in gdf.columns: gdf['COD_DPTO'] = [f"{i:02d}" for i in range(1,len(gdf)+1)]
    gdf['COD_DPTO'] = gdf['COD_DPTO'].astype(str).str.zfill(2)
    gdf = gdf.to_crs(4326)
    gdf_proj = gdf.to_crs(3116)
    return gdf, gdf_proj

