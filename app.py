def spatial_model_selection(y, X, w, name_y='y', name_x=None):
    """
    Rutina automatizada de selección de especificación espacial por ecuación.
    Pruebas: LM lag, LM error, robustos, AIC/BIC, LR.
    Retorna el modelo recomendado y el objeto estimado.
    """
    if name_x is None:
        name_x = [f'x{i}' for i in range(X.shape[1])]

    results = {}

    # 1. OLS + diagnósticos espaciales
    ols = OLS(y, X, w=w, spat_diag=True, moran=True,
              name_y=name_y, name_x=name_x, name_w=W_name)
    results['OLS'] = {
        'model': ols,
        'aic': ols.aic,
        'bic': getattr(ols, 'bic', np.nan),
        'logll': ols.logll,
        'lm_lag': ols.lm_lag[0] if hasattr(ols, 'lm_lag') else np.nan,
        'lm_lag_p': ols.lm_lag[1] if hasattr(ols, 'lm_lag') else np.nan,
        'lm_error': ols.lm_error[0] if hasattr(ols, 'lm_error') else np.nan,
        'lm_error_p': ols.lm_error[1] if hasattr(ols, 'lm_error') else np.nan,
        'rlm_lag': ols.rlm_lag[0] if hasattr(ols, 'rlm_lag') else np.nan,
        'rlm_lag_p': ols.rlm_lag[1] if hasattr(ols, 'rlm_lag') else np.nan,
        'rlm_error': ols.rlm_error[0] if hasattr(ols, 'rlm_error') else np.nan,
        'rlm_error_p': ols.rlm_error[1] if hasattr(ols, 'rlm_error') else np.nan,
    }

    # 2. SAR (ML_Lag)
    try:
        sar = ML_Lag(y, X, w=w, name_y=name_y, name_x=name_x, name_w=W_name)
        results['SAR'] = {
            'model': sar,
            'aic': sar.aic,
            'bic': getattr(sar, 'bic', np.nan),
            'logll': sar.logll,
            'rho': sar.rho,
        }
    except Exception as e:
        results['SAR'] = {'error': str(e)}

    # 3. SEM (ML_Error)
    try:
        sem = ML_Error(y, X, w=w, name_y=name_y, name_x=name_x, name_w=W_name)
        results['SEM'] = {
            'model': sem,
            'aic': sem.aic,
            'bic': getattr(sem, 'bic', np.nan),
            'logll': sem.logll,
            'lambda': sem.lam,
        }
    except Exception as e:
        results['SEM'] = {'error': str(e)}

    # 4. SAC / SARAR (GM_Combo)
    try:
        sac = GM_Combo(y, X, w=w, name_y=name_y, name_x=name_x, name_w=W_name)
        results['SAC'] = {
            'model': sac,
            'aic': getattr(sac, 'aic', np.nan),
            'rho': sac.rho if hasattr(sac, 'rho') else np.nan,
            'lambda': sac.lam if hasattr(sac, 'lam') else np.nan,
        }
    except Exception as e:
        results['SAC'] = {'error': str(e)}

    # 5. SDM (Spatial Durbin) = SAR + WX
    try:
        # Construir WX
        WX = lag_spatial(w, X)
        X_sdm = np.hstack([X, WX])
        name_x_sdm = name_x + [f'W_{nx}' for nx in name_x]
        sdm = ML_Lag(y, X_sdm, w=w, name_y=name_y, name_x=name_x_sdm, name_w=W_name)
        results['SDM'] = {
            'model': sdm,
            'aic': sdm.aic,
            'bic': getattr(sdm, 'bic', np.nan),
            'logll': sdm.logll,
            'rho': sdm.rho,
        }
    except Exception as e:
        results['SDM'] = {'error': str(e)}

    # Decisión basada en LM robustos + AIC
    decision = 'OLS'
    reason = []

    lm = results['OLS']
    if lm['rlm_lag_p'] < 0.05 and lm['rlm_error_p'] >= 0.05:
        decision = 'SAR'
        reason.append("RLM-Lag significativo, RLM-Error no")
    elif lm['rlm_error_p'] < 0.05 and lm['rlm_lag_p'] >= 0.05:
        decision = 'SEM'
        reason.append("RLM-Error significativo, RLM-Lag no")
    elif lm['rlm_lag_p'] < 0.05 and lm['rlm_error_p'] < 0.05:
        # Ambos significativos → comparar AIC de SAR vs SEM vs SAC/SDM
        aics = {}
        for m in ['SAR', 'SEM', 'SAC', 'SDM']:
            if m in results and 'aic' in results[m] and not np.isnan(results[m].get('aic', np.nan)):
                aics[m] = results[m]['aic']
        if aics:
            decision = min(aics, key=aics.get)
            reason.append(f"Ambos LM robustos sig. → menor AIC: {decision}")
        else:
            decision = 'SAC'
            reason.append("Ambos LM robustos sig. → SAC por defecto")
    else:
        reason.append("Ningún LM robusto significativo → OLS")

    # Si SDM tiene mucho mejor AIC, preferirlo
    if 'SDM' in results and 'aic' in results['SDM']:
        best_aic = min([results[m].get('aic', np.inf) for m in ['SAR', 'SEM', 'SAC', 'OLS']
                        if m in results and 'aic' in results[m]])
        if results['SDM']['aic'] < best_aic - 2:  # mejora sustancial
            decision = 'SDM'
            reason.append("SDM mejora AIC > 2 puntos")

    print(f"\n{'='*60}")
    print(f"SELECCIÓN DE MODELO PARA: {name_y}")
    print(f"{'='*60}")
    print(f"LM-Lag     : {lm['lm_lag']:.3f} (p={lm['lm_lag_p']:.4f})")
    print(f"LM-Error   : {lm['lm_error']:.3f} (p={lm['lm_error_p']:.4f})")
    print(f"RLM-Lag    : {lm['rlm_lag']:.3f} (p={lm['rlm_lag_p']:.4f})")
    print(f"RLM-Error  : {lm['rlm_error']:.3f} (p={lm['rlm_error_p']:.4f})")
    print(f"\n>>> Modelo seleccionado: {decision}")
    print(f"    Razones: {'; '.join(reason)}")

    return decision, results

