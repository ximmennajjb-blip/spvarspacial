def load_ipm_dane(path_or_url=None):
    """
    Lee incidencia TOTAL departamental 2018-2025 del anexo oficial.
    Estructura de la hoja IPM_Departamentos:
      fila 12: años (cada uno ocupa 3 columnas: Total, Cabeceras, Centros)
      fila 14+: datos por departamento
      Total del año y → columna excel 2 + 3*índice_año
    """
    url = path_or_url or "https://www.dane.gov.co/files/operaciones/PM/anex-PMultidimensional-Departamental-2025.xlsx"
    local = DATA / "anex-PMultidimensional-Departamental-2025.xlsx"
    if not local.exists():
        print(f"  Descargando {url} ...")
        r = requests.get(url, timeout=90)
        r.raise_for_status()
        local.write_bytes(r.content)
        print(f"  Guardado: {local} ({local.stat().st_size/1024:.0f} KB)")

    import openpyxl
    wb = openpyxl.load_workbook(local, data_only=True)
    assert "IPM_Departamentos" in wb.sheetnames, f"Hojas: {wb.sheetnames}"
    ws = wb["IPM_Departamentos"]

    years = [2018, 2019, 2020, 2021, 2022, 2023, 2024, 2025]
    # columna 1-based del "Total" de cada año
    total_col = {y: 2 + 3 * i for i, y in enumerate(years)}

    rows = []
    for r in range(14, 50):
        nombre = ws.cell(r, 1).value
        if not nombre or not isinstance(nombre, str):
            continue
        nombre = nombre.strip()
        cod = NOMBRE_A_COD.get(nombre)
        if cod is None:
            # intento normalizado
            key = nombre.replace("á", "a").replace("é", "e").replace("í", "i").replace("ó", "o").replace("ú", "u")
            for k, v in NOMBRE_A_COD.items():
                kn = k.replace("á", "a").replace("é", "e").replace("í", "i").replace("ó", "o").replace("ú", "u")
                if kn.lower() == key.lower():
                    cod = v
                    break
        if cod is None:
            print(f"  (aviso) Nombre no mapeado: {nombre}")
            continue
        for y in years:
            val = ws.cell(r, total_col[y]).value
            if val is None:
                continue
            try:
                val = float(val)
            except (TypeError, ValueError):
                continue
            rows.append({"cod_depto": cod, "year": y, "ipm": val})

    ipm = pd.DataFrame(rows)
    assert not ipm.empty, "IPM vacío tras parseo"
    assert ipm["ipm"].min() >= 0
    # Auditoría: 2023 ≠ 2024
    m23 = ipm.loc[ipm.year == 2023, "ipm"].mean()
    m24 = ipm.loc[ipm.year == 2024, "ipm"].mean()
    m25 = ipm.loc[ipm.year == 2025, "ipm"].mean()
    print(f"  Medias IPM Total → 2023: {m23:.2f} | 2024: {m24:.2f} | 2025: {m25:.2f}")
    assert abs(m23 - m24) > 0.05, "IPM 2023 y 2024 no deberían ser casi idénticos"
    print(f"[OK] IPM REAL DANE: {ipm.shape[0]} filas | años {sorted(ipm.year.unique())} | {ipm.cod_depto.nunique()} deptos")
    return ipm

ipm = load_ipm_dane()
