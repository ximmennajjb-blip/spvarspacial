def estimate_and_select(y, X_no_const, w, name):
    X = np.column_stack([np.ones(len(X_no_const)), X_no_const])
    models = {}
    for label, fn in [
        ("OLS", lambda: OLS(y, X, w=w, spat_diag=True, name_y=name)),
        ("SAR", lambda: ML_Lag(y, X, w=w, name_y=name)),
        ("SEM", lambda: ML_Error(y, X, w=w, name_y=name)),
        ("SAC", lambda: GM_Combo_Hom(y, X, w=w, name_y=name)),
    ]:
        try:
            models[label] = fn()
            print(f"  {label} OK")
        except Exception as e:
            print(f"  {label} falló: {e}")
    try:
        WX = lag_spatial(w, X_no_const)
        X_sdm = np.column_stack([np.ones(len(X_no_const)), X_no_const, WX])
        models["SDM"] = ML_Lag(y, X_sdm, w=w, name_y=name)
        print("  SDM OK")
    except Exception as e:
        print(f"  SDM falló: {e}")
    if not models:
        return None, None
    best = min(models.keys(), key=lambda k: getattr(models[k], "aic", np.inf))
    print(f"\n>>> {name}: mejor = {best}")
    try:
        print(models[best].summary)
    except Exception:
        print(models[best])
    return best, models[best]

print("\n----- ECUACIÓN IPM -----")
spec_ipm, mod_ipm = estimate_and_select(y_ipm, X_base, w_est, "IPM")
print("\n----- ECUACIÓN TASA HOMICIDIO -----")
spec_hom, mod_hom = estimate_and_select(y_hom, X_base, w_est, "Tasa_Homicidio")
