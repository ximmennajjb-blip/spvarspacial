def generate_explanation(dept, variable):
    row = gdf_eda[gdf_eda['DEPARTAMENTO']==dept]
    if row.empty: return "Departamento no encontrado"
    row = row.iloc[0]
    if variable=='log_PIB':
        lisa,val,vn = row.get('LISA_PIB','N/A'), row.get('log_PIB',0), 'log(PIB)'
    elif variable=='luces_viirs':
        lisa,val,vn = 'No aplica', row.get('luces_viirs',0), 'Luces VIIRS'
    else:
        lisa,val,vn = row.get('LISA_HOM','N/A'), row.get('tasa_homicidios',0), 'Tasa Homicidios'
    txt = f"### {dept}\n\n**{vn}** = {val:.3f} | LISA = **{lisa}**\n\n"
    if 'High-High' in str(lisa): txt += "Cluster **High-High** → política regional coordinada."
    elif 'Low-Low' in str(lisa): txt += "Cluster **Low-Low** → zona de valores bajos."
    elif 'High-Low' in str(lisa): txt += "Outlier **High-Low** → fenómeno localizado."
    elif 'Low-High' in str(lisa): txt += "Outlier **Low-High**."
    else: txt += "Sin patrón espacial localmente significativo."
    txt += f"\n\n*Modelo usado: PIB={decision_pib} | Hom={decision_hom} | W={W_name}*"
    return txt

