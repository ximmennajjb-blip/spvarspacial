def generar_mapa(year, variable, tipo_mapa, depto_sel):
    try:
        year = int(year)
        sub = panel[panel.year == year].copy()
        if sub.empty:
            return None, None, f"No hay datos para {year}", ""

        mdf = gdf.drop(columns=[c for c in gdf.columns if "nombre_depto" in str(c)], errors="ignore")
        mdf = mdf.merge(sub[["cod_depto", "ipm", "tasa_homicidio"]], on="cod_depto", how="left")
        mdf["nombre_depto"] = mdf["cod_depto"].map(DIVIPOLA)
        mdf = mdf.loc[:, ~mdf.columns.duplicated()]

        if variable == "IPM":
            col, cmap, title = "ipm", "YlOrRd", f"IPM · {year}"
        elif variable == "Tasa Homicidio":
            col, cmap, title = "tasa_homicidio", "RdPu", f"Tasa Homicidios · {year}"
        else:
            mdf["ipm_n"] = (mdf["ipm"] - mdf["ipm"].min()) / (mdf["ipm"].max() - mdf["ipm"].min() + 1e-9)
            mdf["hom_n"] = (mdf["tasa_homicidio"] - mdf["tasa_homicidio"].min()) / (mdf["tasa_homicidio"].max() - mdf["tasa_homicidio"].min() + 1e-9)
            mdf["bivar"] = mdf["ipm_n"] * 0.6 + mdf["hom_n"] * 0.4
            col, cmap, title = "bivar", "inferno", f"IPM × Homicidios · {year}"

        info = ""
        if depto_sel and depto_sel != "Todos":
            row = mdf[mdf["nombre_depto"] == depto_sel]
            if not row.empty:
                r = row.iloc[0]
                info = (f"**{depto_sel}** (`{r['cod_depto']}`)\n\n"
                        f"- IPM: **{r['ipm']:.1f}%**\n"
                        f"- Tasa homicidio: **{r['tasa_homicidio']:.1f}** por 100 mil\n"
                        f"- Año: **{year}**")

        if tipo_mapa == "Estático (Matplotlib)":
            fig, ax = plt.subplots(1, 1, figsize=(8, 9), facecolor="#111")
            ax.set_facecolor("#111")
            mdf.plot(column=col, cmap=cmap, legend=True, ax=ax,
                     edgecolor="white", linewidth=0.35, missing_kwds={"color": "#333"})
            if depto_sel and depto_sel != "Todos":
                sel = mdf[mdf["nombre_depto"] == depto_sel]
                if not sel.empty:
                    sel.boundary.plot(ax=ax, color="cyan", linewidth=2.5)
            ax.set_title(title, color="white", fontsize=13)
            ax.set_axis_off()
            tmp = tempfile.NamedTemporaryFile(suffix=".png", delete=False)
            fig.savefig(tmp.name, dpi=160, bbox_inches="tight", facecolor="#111")
            plt.close(fig)
            return tmp.name, None, f"✓ Mapa estático: {title}", info

        # 3D
        mdf = mdf.copy()
        mdf["lon"] = mdf.geometry.centroid.x
        mdf["lat"] = mdf.geometry.centroid.y
        mdf = mdf.dropna(subset=[col, "lon", "lat"])
        fig = px.scatter_3d(
            mdf, x="lon", y="lat", z=col, color=col,
            hover_name="nombre_depto", color_continuous_scale="Turbo",
            title=f"3D · {title}", template="plotly_dark"
        )
        fig.update_layout(
            height=560, paper_bgcolor="#0d0d0d", font=dict(color="white"),
            scene=dict(
                xaxis=dict(backgroundcolor="#1a1a1a", gridcolor="#333", color="white"),
                yaxis=dict(backgroundcolor="#1a1a1a", gridcolor="#333", color="white"),
                zaxis=dict(backgroundcolor="#1a1a1a", gridcolor="#333", color="white"),
                bgcolor="#0d0d0d"
            )
        )
        return None, fig, f"✓ Mapa 3D: {title}", info

    except Exception as e:
        return None, None, f"Error: {e}\n{traceback.format_exc()}", ""

