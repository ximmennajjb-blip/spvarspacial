# CELDA 9: Estimación final del sistema SpVAR y extracción de coeficientes
# =============================================================================
def estimate_final_model(y, X, w, model_type, name_y, name_x):
    """Estima el modelo seleccionado y retorna objeto + resumen."""
    if model_type == 'OLS':
        mod = OLS(y, X, w=w, spat_diag=True, name_y=name_y, name_x=name_x)
    elif model_type == 'SAR':
        mod = ML_Lag(y, X, w=w, name_y=name_y, name_x=name_x, name_w=W_name)
    elif model_type == 'SEM':
        mod = ML_Error(y, X, w=w, name_y=name_y, name_x=name_x, name_w=W_name)
    elif model_type == 'SAC':
        mod = GM_Combo(y, X, w=w, name_y=name_y, name_x=name_x, name_w=W_name)
    elif model_type == 'SDM':
        WX = lag_spatial(w, X)
        X_sdm = np.hstack([X, WX])
        name_x_sdm = name_x + [f'W_{n}' for n in name_x]
        mod = ML_Lag(y, X_sdm, w=w, name_y=name_y, name_x=name_x_sdm, name_w=W_name)
    else:
        raise ValueError(f"Modelo desconocido: {model_type}")
    return mod

