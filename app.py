# CELDA 11: Descomposición de los cuatro mecanismos de transmisión
# =============================================================================
"""
1. Autodinámica espacial: efecto de Wy (rho) + inercia temporal propia
2. Cruce local: efecto contemporáneo/rezagado entre PIB y homicidios en la misma unidad
3. Relación espacial directa: efecto de vecinos de la misma variable (W*y)
4. Relación espacial cruzada: efecto de vecinos de la otra variable (W*x_cross)
"""

def transmission_channels(model, decision, name_x, var_label):
    """Extrae e interpreta los cuatro canales."""
    betas = model.betas.flatten()
    names = model.name_x if hasattr(model, 'name_x') else name_x

    channels = {
        'autodinamica_espacial': {},
        'cruce_local': {},
        'relacion_espacial_directa': {},
        'relacion_espacial_cruzada': {}
    }

    # Rho (autodinámica espacial de la dependiente)
    rho = getattr(model, 'rho', None)
    if rho is not None:
        channels['autodinamica_espacial']['rho (W*y)'] = rho

    # Coeficientes
    for i, nx in enumerate(names):
        if i >= len(betas)-1:  # evitar rho si está al final
            break
        b = betas[i+1] if decision != 'OLS' else betas[i]  # ajustar por intercepto

        if 'lag' in nx.lower() and var_label.lower() in nx.lower():
            channels['autodinamica_espacial'][nx] = b
        elif 'lag' in nx.lower():
            channels['cruce_local'][nx] = b
        elif nx.startswith('W_') and var_label.lower() in nx.lower():
            channels['relacion_espacial_directa'][nx] = b
        elif nx.startswith('W_'):
            channels['relacion_espacial_cruzada'][nx] = b
        else:
            # Controles locales
            if 'luces' in nx or 'pob' in nx or 'urban' in nx:
                channels['cruce_local'][nx] = b

    print(f"\n--- Canales de transmisión: {var_label} ({decision}) ---")
    for ch, vals in channels.items():
        print(f"\n{ch.upper()}:")
        if vals:
            for k, v in vals.items():
                print(f"  {k}: {v:.4f}")
        else:
            print("  (no presente en esta especificación)")

    return channels

channels_pib = transmission_channels(model_pib, decision_pib, name_x, 'PIB')
