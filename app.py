def load_homicidios(years=range(2018, 2026)):
    """Descarga y agrega homicidios por departamento-año desde SODA API."""
    base = "https://www.datos.gov.co/resource/m8fd-ahd9.csv"
    frames = []
    for y in tqdm(list(years), desc="Descargando homicidios"):
        params = {
            "$where": f"date_extract_y(fecha_hecho)={y}",
            "$limit": 500000,
            "$select": "cod_depto,cantidad"
        }
        try:
            r = requests.get(base, params=params, timeout=120)
            r.raise_for_status()
            df = pd.read_csv(io.StringIO(r.text))
            if df.empty:
                print(f"  Año {y}: sin filas")
                continue
            df["year"] = y
            frames.append(df)
        except Exception as e:
            print(f"  Año {y}: {e}")
    if not frames:
        raise RuntimeError("No se descargaron homicidios reales")
    raw = pd.concat(frames, ignore_index=True)
    raw["cod_depto"] = raw["cod_depto"].astype(str).str.zfill(2)
    raw = raw[raw["cod_depto"].isin(DIVIPOLA)]
    raw["cantidad"] = pd.to_numeric(raw["cantidad"], errors="coerce").fillna(0)
    agg = (raw.groupby(["cod_depto", "year"])["cantidad"]
           .sum().reset_index()
           .rename(columns={"cantidad": "homicidios"}))
    assert (agg["homicidios"] >= 0).all()
    print(f"[OK] Homicidios REALES: {agg.shape[0]} filas | {agg.year.min()}-{agg.year.max()}")
    return agg

