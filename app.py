def safe_moran(panel, gdf, order, var, year):
    sub = panel[(panel.year == year) & (panel.cod_depto.isin(order))].copy()
    if sub.empty or len(sub) < 5:
        return None
    present = [c for c in order if c in set(sub.cod_depto)]
    sub = sub.set_index("cod_depto").loc[present]
    gdf_sub = gdf[gdf.cod_depto.isin(present)].set_index("cod_depto").loc[present].reset_index()
    w_sub = Queen.from_dataframe(gdf_sub, ids=present)
    w_sub.transform = "R"
    return Moran(sub[var].values, w_sub), w_sub, sub[var].values, present

